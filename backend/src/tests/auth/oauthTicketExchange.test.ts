import { describe, it, expect, vi, beforeEach } from 'vitest';
import { OAuthController } from '../../modules/auth/oauth.controller.js';
import {
    DatabaseOAuthTicketStore,
    createOAuthTicket,
    consumeOAuthTicket,
    _clearOAuthTickets,
    redactOAuthTicketInString,
} from '../../utils/oauthTicketStore.js';
import { AuthService } from '../../modules/auth/auth.service.js';
import { env } from '../../config/env.js';
import { AppError } from '../../utils/AppError.js';
import { sanitizeMetadata } from '../../utils/auditLogger.js';
import { prismaMock } from '../setup.js';
import passport from 'passport';

describe('HIGH-03: OAuth Token Leakage & Hardened Multi-Instance Authorization Ticket Exchange', () => {
    beforeEach(async () => {
        vi.clearAllMocks();
        await _clearOAuthTickets();
    });

    describe('1. Distributed / Multi-Instance Store Behavior', () => {
        it('allows ticket creation on Instance A and consumption on Instance B (separate store instances)', async () => {
            // Simulate two distinct backend server nodes sharing the same database client
            const backendNodeA = new DatabaseOAuthTicketStore(prismaMock as any);
            const backendNodeB = new DatabaseOAuthTicketStore(prismaMock as any);

            const ticket = await backendNodeA.createTicket('user-node-shared', { deviceId: 'device-node-a' });
            expect(typeof ticket).toBe('string');
            expect(ticket.length).toBe(64);

            // Node B consumes the ticket generated by Node A
            const consumedOnNodeB = await backendNodeB.consumeTicket(ticket);
            expect(consumedOnNodeB).not.toBeNull();
            expect(consumedOnNodeB?.userId).toBe('user-node-shared');
            expect(consumedOnNodeB?.deviceInfo?.deviceId).toBe('device-node-a');

            // Neither Node A nor Node B can consume it a second time
            const secondAttemptOnNodeA = await backendNodeA.consumeTicket(ticket);
            expect(secondAttemptOnNodeA).toBeNull();

            const secondAttemptOnNodeB = await backendNodeB.consumeTicket(ticket);
            expect(secondAttemptOnNodeB).toBeNull();
        });

        it('handles concurrent attempts to consume the same ticket atomically: exactly one succeeds, other fails', async () => {
            const backendNode1 = new DatabaseOAuthTicketStore(prismaMock as any);
            const backendNode2 = new DatabaseOAuthTicketStore(prismaMock as any);

            const ticket = await backendNode1.createTicket('user-concurrent-race', { deviceId: 'race-device' });

            // Concurrent race: Node 1 and Node 2 simultaneously try to consume the same ticket
            const [result1, result2] = await Promise.all([
                backendNode1.consumeTicket(ticket),
                backendNode2.consumeTicket(ticket),
            ]);

            // Exactly one must succeed and the other must be null (atomic consumption)
            const successes = [result1, result2].filter((r) => r !== null);
            const failures = [result1, result2].filter((r) => r === null);

            expect(successes).toHaveLength(1);
            expect(failures).toHaveLength(1);
            expect(successes[0]?.userId).toBe('user-concurrent-race');
        });

        it('rejects expired tickets across store instances', async () => {
            const store = new DatabaseOAuthTicketStore(prismaMock as any);
            // Create ticket with negative TTL (already expired)
            const expiredTicket = await store.createTicket('user-expired-instance', undefined, -1000);

            const consumed = await store.consumeTicket(expiredTicket);
            expect(consumed).toBeNull();
        });

        it('rejects replayed ticket consumption across store instances', async () => {
            const store = new DatabaseOAuthTicketStore(prismaMock as any);
            const ticket = await store.createTicket('user-replay-test');

            const first = await store.consumeTicket(ticket);
            expect(first).not.toBeNull();

            const replay = await store.consumeTicket(ticket);
            expect(replay).toBeNull();
        });

        it('returns null for an invalid or fabricated ticket', async () => {
            const store = new DatabaseOAuthTicketStore(prismaMock as any);
            const consumed = await store.consumeTicket('non-existent-fabricated-ticket-value');
            expect(consumed).toBeNull();
        });
    });

    describe('2. OAuth Callback Security & URL Leakage Protection', () => {
        it('redirects with single-use authorization ticket and NEVER leaks accessToken or refreshToken in URL', async () => {
            const mockUser = { id: 'user-google-1', email: 'test@gmail.com' };

            vi.spyOn(passport, 'authenticate').mockImplementation((strategy: any, options: any, callback: any) => {
                return (req: any, res: any) => {
                    callback(null, mockUser);
                };
            });

            const req = {
                headers: {
                    'x-device-id': 'device-test-1',
                    'user-agent': 'Vitest-Agent',
                },
                ip: '127.0.0.1',
                socket: { remoteAddress: '127.0.0.1' },
            } as any;

            let redirectedUrl = '';
            const headersSet: Record<string, string> = {};
            const res = {
                setHeader: vi.fn((key: string, value: string) => {
                    headersSet[key.toLowerCase()] = value;
                }),
                redirect: vi.fn((url: string) => {
                    redirectedUrl = url;
                }),
                cookie: vi.fn(),
            } as any;

            OAuthController.googleCallback(req, res);

            // Wait a tick for async callback inside googleCallback
            await new Promise((r) => setTimeout(r, 20));

            expect(res.redirect).toHaveBeenCalledOnce();
            expect(redirectedUrl).toContain(`${env.FRONTEND_URL}/oauth-callback?ticket=`);

            // MUST NOT leak accessToken or refreshToken in URL parameters
            expect(redirectedUrl).not.toContain('accessToken=');
            expect(redirectedUrl).not.toContain('refreshToken=');

            // Verify strict Referrer-Policy and Cache-Control headers on the callback redirect
            expect(headersSet['referrer-policy']).toBe('no-referrer');
            expect(headersSet['cache-control']).toBe('no-store, no-cache, must-revalidate, private');
            expect(headersSet['pragma']).toBe('no-cache');

            // Extract ticket from URL and verify it is valid in shared storage
            const urlObj = new URL(redirectedUrl);
            const ticket = urlObj.searchParams.get('ticket');
            expect(ticket).toBeTruthy();

            const consumed = await consumeOAuthTicket(ticket!);
            expect(consumed?.userId).toBe('user-google-1');
            expect(consumed?.deviceInfo?.deviceId).toBe('device-test-1');
        });
    });

    describe('3. Ticket Exchange Controller, Replay Rejection, & Cookie Security Attributes', () => {
        it('successfully exchanges a valid ticket for access token and sets secure HTTP-only refresh cookie', async () => {
            const ticket = await createOAuthTicket('user-oauth-456', { deviceId: 'dev-abc' });

            vi.spyOn(AuthService, 'generateToken').mockResolvedValueOnce({
                accessToken: 'jwt-access-token-xyz',
                refreshToken: 'jwt-refresh-token-xyz',
                userId: 'user-oauth-456',
            });

            const req = {
                body: { ticket },
                headers: { 'user-agent': 'Chrome' },
                ip: '10.0.0.1',
                socket: { remoteAddress: '10.0.0.1' },
            } as any;

            let jsonResponse: any;
            let statusCode: number = 0;
            const res = {
                cookie: vi.fn(),
                status: vi.fn((code: number) => {
                    statusCode = code;
                    return {
                        json: vi.fn((data: any) => {
                            jsonResponse = data;
                        }),
                    };
                }),
            } as any;

            await OAuthController.exchangeTicket(req, res);

            expect(statusCode).toBe(200);
            expect(jsonResponse).toEqual({
                success: true,
                data: {
                    accessToken: 'jwt-access-token-xyz',
                    userId: 'user-oauth-456',
                },
            });

            // Refresh token must be in HTTP-only cookie with strict security attributes
            expect(res.cookie).toHaveBeenCalledWith(
                'refreshToken',
                'jwt-refresh-token-xyz',
                {
                    httpOnly: true,
                    secure: env.NODE_ENV === 'production',
                    sameSite: 'strict',
                    path: '/api/v1/auth',
                    maxAge: 7 * 24 * 60 * 60 * 1000,
                }
            );
        });

        it('rejects replayed ticket on second exchange attempt', async () => {
            const ticket = await createOAuthTicket('user-replay-guard');

            vi.spyOn(AuthService, 'generateToken').mockResolvedValue({
                accessToken: 'jwt-token-1',
                refreshToken: 'jwt-token-2',
                userId: 'user-replay-guard',
            });

            const req = {
                body: { ticket },
                headers: {},
                ip: '127.0.0.1',
                socket: { remoteAddress: '127.0.0.1' },
            } as any;

            const makeRes = () => ({
                cookie: vi.fn(),
                status: vi.fn().mockReturnValue({ json: vi.fn() }),
            }) as any;

            // First exchange succeeds
            await OAuthController.exchangeTicket(req, makeRes());

            // Second exchange must fail with 400
            await expect(OAuthController.exchangeTicket(req, makeRes())).rejects.toMatchObject({
                statusCode: 400,
                message: 'Invalid or expired authorization ticket',
            });
        });

        it('rejects expired ticket on exchange', async () => {
            const expiredTicket = await createOAuthTicket('user-exp', undefined, -5000);

            const req = {
                body: { ticket: expiredTicket },
                headers: {},
                ip: '127.0.0.1',
                socket: { remoteAddress: '127.0.0.1' },
            } as any;

            const res = { cookie: vi.fn(), status: vi.fn() } as any;

            await expect(OAuthController.exchangeTicket(req, res)).rejects.toMatchObject({
                statusCode: 400,
                message: 'Invalid or expired authorization ticket',
            });
        });

        it('rejects fabricated or unknown ticket on exchange', async () => {
            const req = {
                body: { ticket: 'unknown-ticket-12345' },
                headers: {},
                ip: '127.0.0.1',
                socket: { remoteAddress: '127.0.0.1' },
            } as any;

            const res = { cookie: vi.fn(), status: vi.fn() } as any;

            await expect(OAuthController.exchangeTicket(req, res)).rejects.toMatchObject({
                statusCode: 400,
                message: 'Invalid or expired authorization ticket',
            });
        });
    });

    describe('4. Ticket Redaction in Application & Audit Logs', () => {
        it('redacts ticket query parameter in log strings', () => {
            const rawUrl = 'https://banking.example.com/oauth-callback?ticket=0123456789abcdef0123456789abcdef';
            const redacted = redactOAuthTicketInString(rawUrl);
            expect(redacted).toBe('https://banking.example.com/oauth-callback?ticket=[REDACTED]');
            expect(redacted).not.toContain('0123456789abcdef');
        });

        it('redacts ticket in JSON payloads and error log messages', () => {
            const jsonPayload = '{"ticket": "0123456789abcdef", "action": "exchange"}';
            const redacted = redactOAuthTicketInString(jsonPayload);
            expect(redacted).toBe('{"ticket": "[REDACTED]", "action": "exchange"}');
            expect(redacted).not.toContain('0123456789abcdef');
        });

        it('redacts ticket and oauthticket fields in audit metadata', () => {
            const metadata = {
                userId: 'user-audit-1',
                ticket: 'sensitive-oauth-ticket-value',
                oauthTicket: 'another-secret-ticket',
                clientInfo: 'Chrome on macOS',
            };

            const sanitized: any = sanitizeMetadata(metadata);
            expect(sanitized.ticket).toBeUndefined();
            expect(sanitized.oauthTicket).toBeUndefined();
            expect(sanitized.userId).toBe('user-audit-1');
            expect(sanitized.clientInfo).toBe('Chrome on macOS');
        });
    });
});
